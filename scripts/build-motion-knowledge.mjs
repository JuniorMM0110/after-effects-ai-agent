import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalogPath = path.join(root, "knowledge", "motion-sources.json");
const recipesDir = path.join(root, "knowledge", "recipes");
const curatedDir = path.join(root, "knowledge", "curated");
const synthesizedDir = path.join(root, "knowledge", "synthesized");
const outPath = path.join(root, "packages", "mcp-server", "src", "generated", "motionKnowledge.ts");

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function assertSource(source, seen) {
  if (!/^AE-\d{3}$/.test(source.id)) throw new Error(`Invalid source id: ${source.id}`);
  if (seen.has(source.id)) throw new Error(`Duplicate source id: ${source.id}`);
  seen.add(source.id);
  if (!/^https:\/\/(www\.)?youtube\.com\/watch\?v=/.test(source.url)) throw new Error(`Not a YouTube watch URL: ${source.url}`);
  if (!source.title || !source.category || !source.priority || !Array.isArray(source.tags)) throw new Error(`Incomplete source: ${source.id}`);
}

function assertCurated(recipe, ids) {
  if (!/^CURATED-[A-Z0-9-]+$/.test(recipe.id)) throw new Error(`Invalid curated id: ${recipe.id}`);
  if (ids.has(recipe.id)) throw new Error(`Duplicate curated id: ${recipe.id}`);
  ids.add(recipe.id);
  if (recipe.origin !== "curated" || !recipe.title || !recipe.summary || !Array.isArray(recipe.techniques) || !Array.isArray(recipe.reusableRecipe)) {
    throw new Error(`Incomplete curated recipe: ${recipe.id}`);
  }
  if (typeof recipe.confidence !== "number" || recipe.confidence < 0 || recipe.confidence > 1) {
    throw new Error(`Invalid confidence for ${recipe.id}`);
  }
}

function assertSynthesized(recipe, ids, sourceIds, curatedIds) {
  if (!/^SYNTH-[A-Z0-9-]+$/.test(recipe.id)) throw new Error(`Invalid synthesized id: ${recipe.id}`);
  if (ids.has(recipe.id)) throw new Error(`Duplicate synthesized id: ${recipe.id}`);
  ids.add(recipe.id);
  if (recipe.origin !== "synthesized" || !recipe.title || !recipe.technique || !recipe.summary) throw new Error(`Incomplete synthesized recipe: ${recipe.id}`);
  if (!Array.isArray(recipe.sourceIds) || !Array.isArray(recipe.curatedIds) || !Array.isArray(recipe.reusableRecipe)) throw new Error(`Synthesized provenance missing: ${recipe.id}`);
  for (const sourceId of recipe.sourceIds) if (!sourceIds.has(sourceId)) throw new Error(`Synthesized ${recipe.id} references unknown source ${sourceId}`);
  for (const curatedId of recipe.curatedIds) if (!curatedIds.has(curatedId)) throw new Error(`Synthesized ${recipe.id} references unknown curated recipe ${curatedId}`);
  if (typeof recipe.confidence !== "number" || recipe.confidence < 0 || recipe.confidence > 1) throw new Error(`Invalid confidence for ${recipe.id}`);
}

function assertRecipe(recipe, sourceIds) {
  if (!sourceIds.has(recipe.sourceId)) throw new Error(`Recipe sourceId not in catalog: ${recipe.sourceId}`);
  if (!recipe.summary || !Array.isArray(recipe.techniques) || !Array.isArray(recipe.reusableRecipe)) {
    throw new Error(`Incomplete recipe: ${recipe.sourceId}`);
  }
  if (typeof recipe.confidence !== "number" || recipe.confidence < 0 || recipe.confidence > 1) {
    throw new Error(`Invalid confidence for ${recipe.sourceId}`);
  }
}

const catalog = readJson(catalogPath);
if (catalog.schemaVersion !== 1 || !Array.isArray(catalog.sources)) throw new Error("Unsupported motion catalog schema.");
const seen = new Set();
for (const source of catalog.sources) assertSource(source, seen);

const recipes = [];
if (fs.existsSync(recipesDir)) {
  for (const name of fs.readdirSync(recipesDir).filter((n) => n.endsWith(".json")).sort()) {
    const recipe = readJson(path.join(recipesDir, name));
    assertRecipe(recipe, seen);
    recipes.push(recipe);
  }
}

const curated = [];
const curatedIds = new Set();
if (fs.existsSync(curatedDir)) {
  for (const name of fs.readdirSync(curatedDir).filter((n) => n.endsWith(".json")).sort()) {
    const recipe = readJson(path.join(curatedDir, name));
    assertCurated(recipe, curatedIds);
    curated.push(recipe);
  }
}

const synthesized = [];
const synthesizedIds = new Set();
if (fs.existsSync(synthesizedDir)) {
  for (const name of fs.readdirSync(synthesizedDir).filter((n) => n.endsWith(".json")).sort()) {
    const recipe = readJson(path.join(synthesizedDir, name));
    assertSynthesized(recipe, synthesizedIds, seen, curatedIds);
    synthesized.push(recipe);
  }
}

const generated = `// Generated by scripts/build-motion-knowledge.mjs. Do not edit.
export const MOTION_SOURCES = ${JSON.stringify(catalog.sources, null, 2)} as const;
export const MOTION_RECIPES = ${JSON.stringify(recipes, null, 2)} as const;
export const MOTION_CURATED = ${JSON.stringify(curated, null, 2)} as const;
export const MOTION_SYNTHESIZED = ${JSON.stringify(synthesized, null, 2)} as const;
export const MOTION_KNOWLEDGE_SCHEMA_VERSION = 1 as const;
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
if (process.argv.includes("--check")) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : "";
  if (current !== generated) {
    console.error("motion knowledge generated source is stale; run npm run build:motion-knowledge");
    process.exit(1);
  }
} else {
  fs.writeFileSync(outPath, generated);
  console.log(`motion knowledge: ${catalog.sources.length} sources, ${recipes.length} learned recipes, ${curated.length} curated recipes, ${synthesized.length} synthesized recipes -> ${path.relative(root, outPath)}`);
}
